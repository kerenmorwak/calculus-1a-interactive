function currentReadingUnit(progress) {
  return interactiveChapterOne.units.find((unit) => !getUnitProgressState(unit, progress[unit.id]).passed) || null;
}

function firstHiddenUnit(progress) {
  const current = currentReadingUnit(progress);
  if (!current) return null;
  const currentIndex = interactiveChapterOne.units.findIndex((unit) => unit.id === current.id);
  return interactiveChapterOne.units[currentIndex + 1] || null;
}

function isUnitReadable(unit, progress) {
  const hiddenUnit = firstHiddenUnit(progress);
  if (!hiddenUnit) return true;
  return unitOrder(unit) < unitOrder(hiddenUnit);
}

function unitOrder(unit) {
  return interactiveChapterOne.units.findIndex((candidate) => candidate.id === unit.id);
}

function nextFlowUnit(unit) {
  const index = interactiveChapterOne.units.findIndex((candidate) => candidate.id === unit.id);
  return index >= 0 ? interactiveChapterOne.units[index + 1] || null : null;
}

