function applyQuestionStats(progress, questionStats) {
  const meta = progress[PROGRESS_META_KEY] || {};
  const topics = meta.topicStats || {};
  questionStats.forEach((item) => {
    const topic = item.topic || item.unitTitle || "כללי";
    const current = topics[topic] || {
      topic,
      attempts: 0,
      mistakes: 0,
      totalFirstCheckMs: 0,
      slowAnswers: 0,
      lastSection: item.section || "",
      lastUnitTitle: item.unitTitle || ""
    };
    current.attempts += 1;
    current.mistakes += item.hadMistake ? 1 : 0;
    current.totalFirstCheckMs += item.firstCheckMs || 0;
    current.slowAnswers += item.firstCheckMs > 45000 ? 1 : 0;
    current.lastSection = item.section || current.lastSection;
    current.lastUnitTitle = item.unitTitle || current.lastUnitTitle;
    topics[topic] = current;
  });
  meta.topicStats = topics;
  progress[PROGRESS_META_KEY] = meta;
}

function learnerTopicSummary(progress) {
  const stats = Object.values(progress?.[PROGRESS_META_KEY]?.topicStats || {});
  const scored = stats
    .filter((item) => item.attempts >= 2)
    .map((item) => {
      const accuracy = item.attempts ? (item.attempts - item.mistakes) / item.attempts : 1;
      const avgMs = item.attempts ? item.totalFirstCheckMs / item.attempts : 0;
      const weakness = (1 - accuracy) + Math.min(avgMs / 90000, 0.75) + Math.min((item.slowAnswers || 0) / Math.max(item.attempts, 1), 0.5);
      const reason = item.mistakes ? (item.mistakes === 1 ? "טעות אחת" : `${item.mistakes} טעויות`) : (avgMs > 30000 ? "לקח יותר זמן" : `${Math.round(accuracy * 100)}%`);
      return { ...item, accuracy, avgMs, weakness, reason };
    });
  const weakCandidates = scored.filter((item) => item.mistakes > 0 || item.avgMs > 30000 || item.slowAnswers > 0);
  return {
    weak: [...weakCandidates].sort((a, b) => b.weakness - a.weakness).slice(0, 3),
    strong: [...scored].sort((a, b) => b.accuracy - a.accuracy || a.avgMs - b.avgMs).slice(0, 2)
  };
}

function updateLearnerInsight(progress) {
  const host = document.querySelector("[data-learner-insight]");
  if (!host) return;
  const summary = learnerTopicSummary(progress);
  if (!summary.weak.length && !summary.strong.length) {
    host.hidden = true;
    host.innerHTML = "";
    return;
  }
  host.hidden = false;
  const weak = summary.weak.map((item) => `<li><span>${formatInlineText(item.topic)}</span> <bdi>${escapeHtml(item.reason)}</bdi></li>`).join("");
  const strong = summary.strong.map((item) => `<li><span>${formatInlineText(item.topic)}</span> <bdi>${Math.round(item.accuracy * 100)}%</bdi></li>`).join("");
  host.innerHTML = `
    ${strong ? `<section><h3>הולך טוב</h3><ul>${strong}</ul></section>` : ""}
    ${weak ? `<section class="weak"><h3>כדאי לחזק</h3><ul>${weak}</ul></section>` : ""}
  `;
  typesetMath(host);
}

