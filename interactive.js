    const unit = interactiveChapterOne.units.find((candidate) => candidate.id === blur.dataset.blurUnitId);
    const locked = unit ? !isUnitReadable(unit, progress) : false;
    blur.hidden = !locked;
    blur.classList.toggle("is-active", locked);
