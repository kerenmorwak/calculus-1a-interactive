function lastRenderedPageNumber() {
  return [...document.querySelectorAll(".page[id^='page-']")]
    .map((page) => Number(page.id.replace("page-", "")))
    .filter(Number.isFinite)
    .sort((a, b) => b - a)[0] || interactiveChapterOne.units[interactiveChapterOne.units.length - 1].page;
}

