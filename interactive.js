function updateUnitProgress(unit, updates) {
  const progress = readInteractiveProgress();
  const previous = progress[unit.id] || {};
  const previousState = getUnitProgressState(unit, previous);
  const quizPassed = Boolean(previousState.quizPassed || updates.quizPassed);
  const continued = Boolean(previousState.continued || updates.continued);
  const next = {
    ...previous,
    quizPassed,
    continued,
    passed: isIntroUnit(unit) ? continued : quizPassed,
    updatedAt: new Date().toISOString()
  };
  const coinsAwarded = !previousState.passed && next.passed ? coinsForUnit(unit) : 0;
  if (coinsAwarded) {
    const meta = progress[PROGRESS_META_KEY] || {};
    meta.coins = Math.max(0, Number(meta.coins) || 0) + coinsAwarded;
    meta.lastAward = {
      unitId: unit.id,
      amount: coinsAwarded,
      awardedAt: next.updatedAt
    };
    progress[PROGRESS_META_KEY] = meta;
    next.coinsAwarded = coinsAwarded;
  }

  if (typeof updates.best === "number") next.best = Math.max(previous.best || 0, updates.best);
  if (typeof updates.mistakes === "number") next.mistakes = updates.mistakes;
  if (typeof updates.total === "number") next.total = updates.total;
  if (Array.isArray(updates.lastQuestionIds)) next.lastQuestionIds = updates.lastQuestionIds;
  if (Array.isArray(updates.questionStats)) applyQuestionStats(progress, updates.questionStats);

  progress[unit.id] = next;
  writeInteractiveProgress(progress);
  syncUnitProgressToCloud(unit.id, next);
  if (coinsAwarded) syncCoinEventToCloud(coinsAwarded, "unit_passed", unit.id);
  if (Array.isArray(updates.questionStats)) syncQuestionAttemptsToCloud(updates.questionStats);
  updateInteractiveProgress();
  return {
    ...getUnitProgressState(unit, next),
    coinsAwarded
  };
}

