function purchaseHomeworkHint(key) {
  const progress = readInteractiveProgress();
  const meta = progress[PROGRESS_META_KEY] || {};
  const purchasedHints = meta.purchasedHints || {};
  if (purchasedHints[key]) {
    return { ok: true, already: true, progress };
  }

  const coins = Math.max(0, Number(meta.coins) || 0);
  if (coins < HINT_COST) {
    return { ok: false, coins, progress };
  }

  meta.coins = coins - HINT_COST;
  meta.purchasedHints = {
    ...purchasedHints,
    [key]: {
      cost: HINT_COST,
      purchasedAt: new Date().toISOString()
    }
  };
  progress[PROGRESS_META_KEY] = meta;
  writeInteractiveProgress(progress);
  syncHintPurchaseToCloud(key, HINT_COST);
  syncCoinEventToCloud(-HINT_COST, "hint_purchase", key);
  updateCoinDisplays(progress);
  pulseCoinHuds();
  return { ok: true, already: false, progress };
}

